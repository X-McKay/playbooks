from __future__ import annotations

import argparse
from datetime import date, timedelta
from pathlib import Path

from agentctl.contracts import NAME_PATTERN, PACKAGE_PATTERN
from agentctl.files import add_if_missing, write_files
from agentctl.templates import render_template
from agentctl.ui import status, step, success


def scaffold_agent(args: argparse.Namespace) -> int:
    if not NAME_PATTERN.fullmatch(args.name):
        raise ValueError(
            "agent name must be lowercase letters, digits, and single hyphens"
        )
    if not PACKAGE_PATTERN.fullmatch(args.package):
        raise ValueError("package must be a valid lowercase Python package name")

    root = args.root.resolve()
    module_name = args.name.replace("-", "_")
    agent_dir = root / "src" / args.package / "agents" / module_name
    temporal = args.with_temporal or args.execution_class != "ephemeral"

    files: dict[Path, str] = {
        agent_dir / "__init__.py": '"""Agent package generated by agentctl."""\n',
        agent_dir / "agent.yaml": _agent_spec(args, module_name, temporal),
        agent_dir / "factory.py": _factory(args.package, module_name),
        agent_dir / "dependencies.py": _dependencies(),
        agent_dir / "models.py": _models(),
        agent_dir / "instructions" / "base.md": _instructions(args.name),
        agent_dir / "skills" / ".gitkeep": "",
        agent_dir / "tools" / ".gitkeep": "",
        root / "docs" / "risk-assessments" / f"{args.name}.yaml": _risk_assessment(
            args
        ),
    }

    add_if_missing(files, root / "src" / args.package / "__init__.py", "")
    add_if_missing(files, root / "src" / args.package / "agents" / "__init__.py", "")

    if temporal:
        files.update(_temporal_files(root, args.package, module_name))
    if args.execution_class == "human_governed":
        files[
            root / "src" / args.package / "policy" / "approvals" / f"{module_name}.yaml"
        ] = _approval_policy()
    if args.risk_tier in {"medium", "high", "critical"}:
        files[root / "docs" / "threat-models" / f"{args.name}.md"] = _threat_model(
            args.name
        )
    if args.with_evals:
        files.update(_eval_files(root, args.name, module_name))

    with status("Creating the golden-path agent package…"):
        write_files(files, force=args.force)
    success(
        "Agent scaffold created",
        (
            ("Agent", args.name),
            ("Execution", args.execution_class),
            ("Risk", args.risk_tier),
            ("Files", str(len(files))),
            ("Root", str(root)),
        ),
    )
    step(f"Next: agentctl validate --root {root}")
    if args.with_evals:
        step(f"Then: agentctl eval run {args.name} --root {root}")
    return 0


def _agent_spec(args: argparse.Namespace, module_name: str, temporal: bool) -> str:
    approval = (
        f"  approval_policy: src/{args.package}/policy/approvals/{module_name}.yaml\n"
        if args.execution_class == "human_governed"
        else ""
    )
    return render_template(
        "agent/agent-spec.tmpl",
        args_name=args.name,
        args_owner=args.owner,
        args_execution_class=args.execution_class,
        args_risk_tier=args.risk_tier,
        str_temporal_lower=str(temporal).lower(),
        module_name=module_name,
        approval=approval,
    )


def _factory(package: str, module_name: str) -> str:
    return render_template(
        "agent/factory.tmpl", package=package, module_name=module_name
    )


def _dependencies() -> str:
    return render_template("agent/dependencies.tmpl")


def _models() -> str:
    return render_template("agent/models.tmpl")


def _instructions(name: str) -> str:
    return f"""# {name} instructions

- Separate verified facts, assumptions, and recommendations.
- Use only explicitly enabled skills and tools.
- Stop and escalate when authorization, evidence, or budget is insufficient.
"""


def _temporal_files(root: Path, package: str, module_name: str) -> dict[Path, str]:
    workflows = root / "src" / package / "workflows"
    activities = root / "src" / package / "activities"
    files = {
        workflows
        / f"{module_name}.py": '''"""Deterministic Temporal coordination for this agent."""

# Keep model calls, network I/O, files, randomness, and wall-clock decisions in
# activities. Add workflow code using the Temporal SDK version pinned by the app.
''',
        activities
        / f"{module_name}.py": '''"""Nondeterministic activities for this agent."""

# Build and run the PydanticAI agent here. Configure bounded timeouts, retries,
# idempotency, heartbeats, and stable application failure types.
''',
    }
    add_if_missing(files, workflows / "__init__.py", "")
    add_if_missing(files, activities / "__init__.py", "")
    return files


def _approval_policy() -> str:
    return """required: true
bind_to_action_hash: true
authenticated_actor: true
expires_after_seconds: 86400
audit_required: true
"""


def _threat_model(name: str) -> str:
    return render_template("agent/threat-model.tmpl", name=name)


def _risk_assessment(args: argparse.Namespace) -> str:
    impact, likelihood = {
        "low": (1, 1),
        "medium": (2, 2),
        "high": (2, 4),
        "critical": (3, 4),
    }[args.risk_tier]
    assessed_at = date.today()
    review_days = {"low": 365, "medium": 180, "high": 90, "critical": 30}
    review_by = assessed_at + timedelta(days=review_days[args.risk_tier])
    decision = "no_go" if args.risk_tier == "critical" else "conditional_go"
    dimension_review = "\n".join(
        f"  {dimension}:\n"
        "    status: applicable\n"
        f"    rationale: Review the {dimension.replace('_', ' ')} dimension for this use case."
        for dimension in (
            "financial",
            "operational",
            "reputational",
            "legal",
            "security",
            "privacy",
            "regulatory",
            "human_impact_safety",
        )
    )
    return render_template(
        "agent/risk-assessment.tmpl",
        args_name=args.name,
        assessed_at_isoformat=assessed_at.isoformat(),
        review_by_isoformat=review_by.isoformat(),
        args_owner=args.owner,
        args_execution_class=args.execution_class,
        dimension_review=dimension_review,
        args_risk_tier=args.risk_tier,
        decision=decision,
        impact=impact,
        likelihood=likelihood,
    )


def _eval_files(root: Path, agent_name: str, module_name: str) -> dict[Path, str]:
    eval_dir = root / "evals" / module_name
    return {
        eval_dir / "README.md": f"""# {agent_name} evaluations

Replace the fail-closed placeholder in `run.py` with Pydantic Evals datasets and
evaluators. Preserve the normalized report fields consumed by `agentctl`.
""",
        eval_dir / "run.py": _eval_runner(agent_name),
        eval_dir / "release-policy.yaml": _release_policy(),
        eval_dir / "datasets" / "smoke" / ".gitkeep": "",
        eval_dir / "datasets" / "regression" / ".gitkeep": "",
        eval_dir / "datasets" / "safety" / ".gitkeep": "",
        eval_dir / "baselines" / ".gitkeep": "",
    }


def _eval_runner(agent_name: str) -> str:
    return render_template("agent/eval-runner.tmpl", agent_name=agent_name)


def _release_policy() -> str:
    return render_template("agent/release-policy.tmpl")
